"""Summarize peak signature-table sizes in the recorded experiments.

This reads existing results; run verify.py, families.py, and benchmark.py first
to regenerate the underlying experiments. No timing or asymptotic inference is
made here. The peak is over every intermediate and completed table in one run.
"""
import argparse
import csv
import hashlib
import json
from pathlib import Path


def summarize(directory):
    with (directory / 'all_profiles.csv').open(newline='') as handle:
        exhaustive = list(csv.DictReader(handle))
    with (directory / 'benchmarks.csv').open(newline='') as handle:
        benchmarks = list(csv.DictReader(handle))
    spiders = json.loads((directory / 'spider_family.json').read_text())

    by_order = []
    for n in sorted({int(row['n']) for row in exhaustive}):
        rows = [row for row in exhaustive if int(row['n']) == n]
        peak = max(int(row['peak_states']) for row in rows)
        by_order.append({
            'n': n, 'trees': len(rows), 'peak_states': peak,
            'attaining_tree_indices': [int(row['index']) for row in rows
                                      if int(row['peak_states']) == peak],
        })

    families = [{'family': row['family'], 'n': int(row['n']),
                 'peak_states': int(row['peak_states'])} for row in benchmarks]
    spider_rows = [{key: row[key] for key in ('r', 'n', 'peak_states')}
                   for row in spiders]
    inputs = ('all_profiles.csv', 'benchmarks.csv', 'spider_family.json')
    return {
        'metric': 'Maximum number of signatures in any one partial or completed table.',
        'scope': 'Recorded root and child order; not maximized over alternative orders.',
        'root': 0,
        'child_order': {
            'exhaustive_and_benchmarks': 'Lexicographically sorted undirected edges.',
            'spiders': 'Long arm followed by the two short arms (families.spider).',
        },
        'prufer_seed': '291026 + n; one sequence per order, generated by benchmark.py.',
        'source_sha256': {name: hashlib.sha256((directory / name).read_bytes()).hexdigest()
                          for name in inputs},
        'exhaustive_trees': len(exhaustive),
        'exhaustive_max_peak_states': max(row['peak_states'] for row in by_order),
        'exhaustive_by_order': by_order,
        'benchmarks': families,
        'spider_max_peak_states': max(row['peak_states'] for row in spider_rows),
        'spiders': spider_rows,
        'interpretation': 'Finite observations do not settle tightness of the O(s^2) state bound.',
    }


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--results', type=Path,
                        default=Path(__file__).resolve().parent / 'results')
    args = parser.parse_args()
    report = summarize(args.results)
    destination = args.results / 'state_counts.json'
    destination.write_text(json.dumps(report, indent=2) + '\n')
    print(f"Saved {destination.name}: exhaustive peak "
          f"{report['exhaustive_max_peak_states']}, spider peak "
          f"{report['spider_max_peak_states']}.")
